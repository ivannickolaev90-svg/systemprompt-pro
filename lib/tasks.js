const clean = (v) => String(v).replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, '').replace(/[\u2028\u2029]/g, '\n').trim();

// Проверяет и нормализует поля формы. Возвращает { fields } или { error, field }
export function validateFields(task, input) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) return { error: 'bad_fields' };
  const out = {};
  for (const f of task.fields) {
    let v = input[f.name];
    v = typeof v === 'string' ? clean(v) : '';
    if (f.type === 'select') {
      if (v && !f.options.includes(v)) return { error: 'bad_option', field: f.name };
    } else if (v.length > (f.max || 300)) {
      return { error: 'too_long', field: f.name };
    }
    if (f.required && !v) return { error: 'required', field: f.name };
    out[f.name] = v;
  }
  return { fields: out };
}

