// Делит текст на отдельные отзывы: по пустым строкам, а если их нет — по строкам
export function splitReviews(text) {
  const t = String(text || '').trim();
  let parts = t.split(/\n\s*\n/).map((x) => x.trim()).filter(Boolean);
  if (parts.length < 2) parts = t.split(/\n/).map((x) => x.trim()).filter(Boolean);
  return parts;
}

