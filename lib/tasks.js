const withProfile = (text, profile) => profile
  ? 'Сведения о моём магазине/бизнесе (учитывай их, но не выдумывай сверх них):\n<<<\n' + profile + '\n>>>\n\n' + text
  : text;

export function buildMessages(task, fields, tweak, previous, profile) {
  const msgs = [
    { role: 'system', content: task.system + '\n\nОбщие правила:\n' + COMMON_RULES },
    { role: 'user', content: withProfile(task.build(fields), profile) }
  ];
  if (tweak && TWEAKS[tweak] && previous) {
    msgs.push({ role: 'assistant', content: previous });
    msgs.push({ role: 'user', content: TWEAKS[tweak] + ' Выдай только новый вариант целиком.' });
  }
  return msgs;
}

